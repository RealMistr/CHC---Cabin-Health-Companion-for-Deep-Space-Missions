/* Packs the real Curiosity (MSL) RAD cruise dose rate from data/radiation-msl-cruise.json into js/curiosity-rad.js,
 * so the sample crew can use it offline (a page opened from file:// cannot load JSON files).
 * Times are stored as seconds after the first sample; js/sample.js moves them so the data ends now.
 * Run from the project folder: node tools/build-curiosity-js.js */
const fs = require("fs"), path = require("path");
const src = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data", "radiation-msl-cruise.json"), "utf8"));
const s = src.series[0].samples, t0 = Date.parse(s[0][0]);
const out = {
  source: "NASA Planetary Data System, Curiosity (Mars Science Laboratory) RAD, cruise to Mars Dec 2011 - Jan 2012, data set MSL-M-RAD-3-RDR-V1.0. Detector E (tissue-like plastic) absorbed dose rate in µGy/h.",
  unit: "µGy/h",
  dt: s.map(function (x) { return Math.round((Date.parse(x[0]) - t0) / 1000); }),
  v: s.map(function (x) { return x[1]; })
};
const js = "/* Real radiation data measured by NASA's Curiosity rover (RAD instrument) on its cruise to Mars.\n * Generated by tools/build-curiosity-js.js from data/radiation-msl-cruise.json. Do not edit by hand. */\n" +
  "(function (g) { var H = g.Halo = g.Halo || {}; H.curiosity = " + JSON.stringify(out) + "; })(typeof window !== \"undefined\" ? window : globalThis);\n";
const file = path.join(__dirname, "..", "js", "curiosity-rad.js");
fs.writeFileSync(file, js);
console.log("Wrote " + file + " (" + s.length + " samples, " + Math.round(js.length / 1024) + " KB)");
